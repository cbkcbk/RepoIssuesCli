using System.Text.Json.Nodes;
using RepoCli.Core.Cli.Plugin;

namespace RepoInfraCli.Cli.Plugin;

public sealed class InfraPlugin : IPluginSource
{
    public const string Name = "infra";
    public const string HooksPath = "hooks/hooks.json";
    const string Summary = "Write and run infrastructure stored in the repository with the infra CLI, with a guard hook that asks before infra changes anything and an edit hook that validates .repo-infra Luau.";

    public static IReadOnlyList<GeneratedFile> Generate(string repoRoot) =>
        PluginGenerator.Generate(repoRoot, new PluginDefinition(Name, Summary, RepoCliApp.Version(typeof(InfraPlugin).Assembly), Skill(), [new GeneratedFile(HooksPath, Hooks())]));

    static string Hooks() => PluginGenerator.Json(new JsonObject
    {
        ["description"] = "infra plugin: ask before infra commands that change cloud resources, hosts, databases or secrets (deny where an ask might not prompt), and validate .repo-infra Luau offline after Edit/Write.",
        ["hooks"] = new JsonObject
        {
            ["PreToolUse"] = new JsonArray(Matcher("Bash|PowerShell", "shell", 10)),
            ["PostToolUse"] = new JsonArray(Matcher("Edit|Write|MultiEdit", "edit", 30)),
        },
    });

    static JsonObject Matcher(string matcher, string hookEvent, int timeout) => new()
    {
        ["matcher"] = matcher,
        ["hooks"] = new JsonArray(new JsonObject
        {
            ["type"] = "command",
            ["command"] = $"infra hook {hookEvent}",
            ["timeout"] = timeout,
        }),
    };

    static string Skill() =>
        $$"""
          ---
          name: {{Name}}
          description: Write and run the repo's infrastructure in `.repo-infra/` with the `infra` CLI - Luau scripts that declare cloud resources, hosts, plays, apps, Postgres databases and secrets, planned and applied without a state file. Use when the repo contains `.repo-infra/`, when editing `infra.luau` or any `.repo-infra/**/*.luau`, and when deploying, provisioning, configuring hosts, managing secrets, restoring or copying a database, or reading infra plan output.
          ---

          <!-- Generated by `infra generate-plugin` (debug build). Edit RepoInfraCli/Cli/Plugin/InfraPlugin.cs and regenerate. -->

          # infra

          `infra` evaluates `.repo-infra/infra.luau` into a graph of cloud resources, hosts, plays and apps without side effects, then pulls the live state, diffs it and pushes the difference. There is no state file: each live resource carries a marker naming its owner, so every plan is computed fresh.

          ## Safety rules

          - **Never change live infrastructure without the user's approval in this turn.** These commands change things: `apply`, `adopt`, `destroy`, `restore` (without `--list`), `db copy`, `secrets set`, `secrets init`, `secrets recipients add|remove`, and any command with `--accept-new-hosts`. The plugin's guard hook asks the user before they run, and refuses them in permission modes that might not ask; then ask the user to run the command themselves with `! infra ...`.
          - **Plan before every apply, in the same turn.** Run `infra plan --json` and show the user the counts from `summary`, then every `remove` (`-`) and `replace` (`-/+`) change in full, every copy into a protected target, and every entry in `problems`. Only then run `infra apply --yes --json`. `apply` plans again, so if files changed or time passed since the plan, plan again first.
          - **Never see a secret value.** `infra secrets show` is blocked. To store a value, ask the user to run `! infra secrets set <name>`; for a random one run `infra secrets generate <name>`. Never write a secret value into a `.luau` file, a command line, a log or a commit, and never edit `.repo-infra/secrets.yaml` by hand.
          - **Check the env.** When `.repo-infra/envs/` exists every command needs `--env <env>`, and each env is a separate owner. Name the env when you ask for approval.

          ## Calling the CLI

          - Pass `--json` on every call. It never prompts: a command that needs confirmation fails with exit code 2 unless given `--yes` (plus `--confirm <owner>` for `destroy` and for copies into protected targets).
          - Option details for any command: `infra <command> --help`.
          - Missing from PATH: `dotnet tool install -g RepoInfraCli`.

          | Exit code | Meaning |
          |---|---|
          {{PluginGenerator.ExitCodeRows(typeof(InfraExitCodes))}}

          ## Commands

          | Command | Purpose |
          |---|---|
          {{PluginGenerator.CommandRows(PluginGenerator.Commands(Name, console => InfraApp.Create(console, console)))}}

          `infra hook` is called by this plugin's hooks; you don't run it.

          ## Terms

          - **Project**: the name `infra.project` declares; it is in every marker.
          - **Env**: the environment chosen with `--env` (`infra.env` in Luau); optional.
          - **Owner**: project and env together, written `<project>-<env>`, or `<project>` without an env. Markers belong to an owner; `--confirm <owner>` types it.
          - **Marker**: the tag, comment or name prefix on a live resource that says which owner it belongs to. A resource without one is never touched until `infra adopt`.
          - **Protected**: a resource with `protect`; it can't be deleted or replaced.
          - **Exported**: a value another repo may import with `repo.provider`, and the resource behind it; implicitly protected.
          - **Play**: roles (Luau functions of host tasks) run on a set of hosts.

          ## Writing infra.luau

          The API is in the type stubs that `infra init` writes to `.repo-infra/.luau/@infra/`: `init.luau` (`require("@infra")`), `digitalocean`, `cloudflare`, `compose`, `dotnet`, `postgres`, `traefik`, `repo` and `types`. Read the stub of a module before using it; run `infra init` again to refresh the stubs after upgrading the CLI. Traps:

          1. Values only known after apply (ids, addresses) are opaque outputs. Pass them on to other options; you can't branch on them, compare them or build strings from them in Luau.
          2. The sandbox has no `io`, `os` or network, and `require` only loads `@infra` modules and files in `.repo-infra/`.
          3. Secrets: reference them as `secret "x/y"`, never as values. A value for one env goes in `<env>/x/y`, which wins over `x/y`.
          4. Differences between envs are Luau branches on `infra.env`, not separate files.
          5. Firewall, SSH key and registry names (and project and env names) must not contain `--`, and those resources can't be `protect`ed or exported.
          6. Removing a resource from `infra.luau` plans its deletion unless it is protected or exported; `apply` refuses any delete or replace without `--allow-destroy`. Pass `--allow-destroy` only when the user approved exactly those deletes.
          7. Luau types aren't checked; `validate` only catches mistakes at runtime, so evaluate after every change.

          After you edit a `.repo-infra/**/*.luau` file, the plugin's edit hook runs `infra validate --offline` (no container settings check, other repos only as cached) and stops you on errors. Before `plan`, run the full `infra validate --json`.

          ## Typical flows

          - Change infrastructure: edit the Luau, `infra validate --json`, `infra plan --json`, show the plan, wait for the user, `infra apply --yes --json`. On exit code 5 (partially applied) plan again and report what is left.
          - Drift check: `infra plan --exit-code --json`; exit code 6 means live state differs from `infra.luau`.
          - Restore: `infra restore <database> --list --json` first, then let the user pick the dump or time.
          """;
}