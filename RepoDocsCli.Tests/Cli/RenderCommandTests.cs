using System.Text.Json;

namespace RepoDocsCli.Tests.Cli;

public class RenderCommandTests
{
    TempRepo repo = null!;

    [SetUp]
    public void SetUp() => repo = new TempRepo();

    [TearDown]
    public void TearDown() => repo.Dispose();

    string ClaudeMdPath => Path.Combine(repo.Root, "CLAUDE.md");

    string ReadClaudeMd() => File.ReadAllText(ClaudeMdPath);

    void InitWithBilling()
    {
        repo.Store.Initialize();
        repo.WriteDocsFile("repo.yaml", "entries:\n  - id: style\n    kind: rule\n    summary: Use tabs\n");
        repo.WriteDocsFile("billing.yaml",
            "feature: billing\nstatus: shipped\nsummary: Invoices\nentries:\n  - id: rounding\n    kind: rule\n    summary: Round half to even\n  - id: vat\n    kind: fact\n    summary: VAT is cached\n");
    }

    [Test]
    public void RenderCreatesClaudeMdWhenMissing()
    {
        InitWithBilling();

        var result = repo.Run("render");

        Assert.That(result.ExitCode, Is.Zero, result.Errors);
        Assert.That(result.Output, Is.EqualTo($"Created {ClaudeMdPath}\n"));
        Assert.That(ReadClaudeMd(), Is.EqualTo(
            """
                <!-- docs:begin (generated by docs render; change docs with the docs CLI, not here) -->
                ## Repo

                ### repo/style: Use tabs

                ## Features

                Read a feature with `docs show <id>` (or one entry with `docs show <id>/<entry>`) and search with `docs find <query>`. Never read or edit `.repo-docs/` files directly.

                - billing [shipped]: Invoices
                  - billing/rounding: Round half to even
                <!-- docs:end -->

                """.ReplaceLineEndings("\n")));
    }

    [Test]
    public void RenderAppendsToAFileWithoutMarkersAndThenUpdatesInPlace()
    {
        InitWithBilling();
        File.WriteAllText(ClaudeMdPath, "# Global rules\r\n\r\nBe brief.\r\n");

        Assert.That(repo.Run("render").Output, Is.EqualTo($"Updated {ClaudeMdPath}\n"));
        var first = ReadClaudeMd();
        Assert.That(first, Does.StartWith("# Global rules\r\n\r\nBe brief.\r\n\n<!-- docs:begin"));

        File.WriteAllText(ClaudeMdPath, first + "\r\nAfter the block.\r\n");
        repo.WriteDocsFile("billing.yaml", "feature: billing\nsummary: Payments\n");

        repo.Run("render");

        var second = ReadClaudeMd();
        Assert.That(second, Does.StartWith("# Global rules\r\n\r\nBe brief.\r\n\n<!-- docs:begin"));
        Assert.That(second, Does.EndWith("<!-- docs:end -->\n\r\nAfter the block.\r\n"));
        Assert.That(second, Does.Contain("- billing [proposed]: Payments\n"));
        Assert.That(second, Does.Not.Contain("Invoices"));
    }

    [Test]
    public void RenderWhenUpToDateWritesNothing()
    {
        InitWithBilling();
        repo.Run("render");
        var written = File.GetLastWriteTimeUtc(ClaudeMdPath);

        var result = repo.Run("render");

        Assert.That(result.Output, Is.EqualTo($"Up to date: {ClaudeMdPath}\n"));
        Assert.That(File.GetLastWriteTimeUtc(ClaudeMdPath), Is.EqualTo(written));
    }

    [Test]
    public void CheckExitsWithOneWhenStaleAndWritesNothing()
    {
        InitWithBilling();

        var missing = repo.Run("render", "--check");

        Assert.That(missing.ExitCode, Is.EqualTo(ExitCodes.ValidationFailed));
        Assert.That(missing.Output, Is.EqualTo("CLAUDE.md is stale; run docs render.\n"));
        Assert.That(File.Exists(ClaudeMdPath), Is.False);

        repo.Run("render");
        Assert.That(repo.Run("render", "--check").ExitCode, Is.Zero);

        repo.WriteDocsFile("search.yaml", "feature: search\n");
        var before = ReadClaudeMd();
        Assert.That(repo.Run("render", "--check").ExitCode, Is.EqualTo(ExitCodes.ValidationFailed));
        Assert.That(ReadClaudeMd(), Is.EqualTo(before));
    }

    [Test]
    public void JsonReportsPathChangedAndStale()
    {
        InitWithBilling();

        var check = JsonDocument.Parse(repo.Run("render", "--check", "--json").Output).RootElement;
        var render = repo.Run("render", "--json");
        var json = JsonDocument.Parse(render.Output).RootElement;
        var again = JsonDocument.Parse(repo.Run("render", "--json").Output).RootElement;

        Assert.That(render.Errors, Is.Empty);
        Assert.That(check.GetProperty("stale").GetBoolean(), Is.True);
        Assert.That(check.GetProperty("changed").GetBoolean(), Is.False);
        Assert.That(json.GetProperty("path").GetString(), Is.EqualTo(ClaudeMdPath));
        Assert.That(json.GetProperty("created").GetBoolean(), Is.True);
        Assert.That(json.GetProperty("changed").GetBoolean(), Is.True);
        Assert.That(json.GetProperty("stale").GetBoolean(), Is.True);
        Assert.That(again.GetProperty("changed").GetBoolean(), Is.False);
        Assert.That(again.GetProperty("stale").GetBoolean(), Is.False);
    }

    [Test]
    public void RenderGitAddsANewClaudeMd()
    {
        repo.InitGit();
        InitWithBilling();
        repo.Git("commit", "-q", "-m", "docs");

        repo.Run("render");

        Assert.That(repo.Git("diff", "--cached", "--name-only"), Is.EqualTo("CLAUDE.md\n"));
    }

    [Test]
    public void RenderDoesNotStageAnExistingClaudeMd()
    {
        repo.InitGit();
        InitWithBilling();
        File.WriteAllText(ClaudeMdPath, "# Rules\n");
        repo.Git("add", "-A");
        repo.Git("commit", "-q", "-m", "docs");

        repo.Run("render");

        Assert.That(repo.Git("diff", "--cached", "--name-only"), Is.Empty);
        Assert.That(repo.Git("status", "--porcelain"), Is.EqualTo(" M CLAUDE.md\n"));
    }

    [Test]
    public void FileErrorsAreReportedOnStderrAndTheRestIsRendered()
    {
        InitWithBilling();
        repo.WriteDocsFile("broken.yaml", "feature: [unclosed");

        var result = repo.Run("render");

        Assert.That(result.ExitCode, Is.Zero);
        Assert.That(result.Errors, Does.Contain("broken.yaml"));
        Assert.That(ReadClaudeMd(), Does.Contain("- billing [shipped]: Invoices"));
    }

    [Test]
    public void BrokenMarkersAreAValidationError()
    {
        InitWithBilling();
        File.WriteAllText(ClaudeMdPath, "<!-- docs:begin -->\nno end\n");

        var result = repo.Run("render");

        Assert.That(result.ExitCode, Is.EqualTo(ExitCodes.ValidationFailed));
        Assert.That(result.Errors, Does.Contain("CLAUDE.md"));
        Assert.That(ReadClaudeMd(), Is.EqualTo("<!-- docs:begin -->\nno end\n"));
    }

    [Test]
    public void RenderWithoutRepoDocsIsAUsageError()
    {
        var result = repo.Run("render");

        Assert.That(result.ExitCode, Is.EqualTo(ExitCodes.Usage));
        Assert.That(result.Errors, Does.Contain("docs init"));
        Assert.That(File.Exists(ClaudeMdPath), Is.False);
        Assert.That(repo.Store.IsInitialized, Is.False);
    }
}