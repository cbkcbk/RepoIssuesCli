using RepoDocsCli.Features.Docs;
using RepoDocsCli.Features.Import;

namespace RepoDocsCli.Tests.Features;

public class ImportSplitterTests
{
    static List<ImportCandidate> Candidates(string markdown) =>
        MarkdownReader.Read(markdown).Sections.SelectMany(section => ImportSplitter.Split(section, headingIsSummary: true)).ToList();

    [Test]
    public void EachHeadingWithContentBecomesOneEntryAndParentsWithoutContentAreSkipped()
    {
        var candidates = Candidates(
            """
            # Guide

            ## Build

            Run the build script.

            ### Release

            Tag the commit.
            Then push.
            """);

        Assert.That(candidates.Select(candidate => (candidate.Summary, candidate.Body, candidate.Line)), Is.EqualTo(new[]
        {
            ("Build", "Run the build script.", 3),
            ("Release", "Tag the commit.\nThen push.", 7),
        }));
        Assert.That(candidates[1].Headings, Is.EqualTo(new[] { "Guide", "Build", "Release" }));
    }

    [Test]
    public void HeadingsInsideCodeFencesAreContent()
    {
        var candidates = Candidates("## Script\n\n```sh\n# not a heading\necho hi\n```\n");

        Assert.That(candidates, Has.Count.EqualTo(1));
        Assert.That(candidates[0].Body, Is.EqualTo("```sh\n# not a heading\necho hi\n```"));
    }

    [Test]
    public void TextBeforeTheFirstHeadingUsesItsFirstSentenceAsSummary()
    {
        var candidate = Candidates("This repo ships two tools. Both share a core.\nMore text.\n\n# Next\n").Single();

        Assert.That(candidate.Summary, Is.EqualTo("This repo ships two tools"));
        Assert.That(candidate.Body, Is.EqualTo("Both share a core.\nMore text."));
        Assert.That(candidate.Line, Is.EqualTo(1));
    }

    [Test]
    public void ALeafBulletListBecomesOneEntryPerBullet()
    {
        var candidates = Candidates(
            """
            ## Style

            - Use tabs.
            - Never use regions. They hide code.
              Even in tests.
            * Prefer records, e.g. for results
            """);

        Assert.That(candidates.Select(candidate => (candidate.Summary, candidate.Body, candidate.Line)), Is.EqualTo(new (string, string?, int)[]
        {
            ("Use tabs", null, 3),
            ("Never use regions", "They hide code.\nEven in tests.", 4),
            ("Prefer records, e.g. for results", null, 6),
        }));
    }

    [TestCase("## Style\n\nIntro line.\n\n- One\n- Two\n", TestName = "Text besides the bullets")]
    [TestCase("## Style\n\n- Only one\n", TestName = "A single bullet")]
    [TestCase("## Style\n\n- One\n- Two\n\n### Nested\n\nText.\n", TestName = "A section with subsections")]
    [TestCase("## How to release\n\n- Bump\n- Tag\n", TestName = "A howto heading")]
    public void BulletsStayTogether(string markdown) =>
        Assert.That(Candidates(markdown)[0].Summary, Is.EqualTo(markdown.Contains("How to") ? "How to release" : "Style"));

    [Test]
    public void GeneratedBlockAndImportLinesAreSkipped()
    {
        var document = MarkdownReader.Read(
            """
            # Rules

            @docs/style.md
            - @AGENTS.md
            Keep it short.

            <!-- docs:begin (generated by docs render; edit .repo-docs instead) -->
            ## Repo

            ### repo/x: generated
            <!-- docs:end -->

            ## After

            Still imported.
            """);

        var candidates = document.Sections.SelectMany(section => ImportSplitter.Split(section, headingIsSummary: true)).ToList();

        Assert.That(candidates.Select(candidate => (candidate.Summary, candidate.Body)), Is.EqualTo(new[]
        {
            ("Rules", "Keep it short."),
            ("After", "Still imported."),
        }));
        Assert.That(document.Imports.Select(line => (line.Number, line.Text)), Is.EqualTo(new[] { (3, "@docs/style.md"), (4, "- @AGENTS.md") }));
    }

    [TestCase("Conventions", "Always run the formatter.", "rule")]
    [TestCase("Style", "Don't use regions.", "rule")]
    [TestCase("Locks", "Be careful: the lock is not reentrant.", "gotcha")]
    [TestCase("Gotchas", "The cache lives an hour.", "gotcha")]
    [TestCase("Release", "1. Bump the version.\n2. Tag it.", "howto")]
    [TestCase("How to test", "Use the script.", "howto")]
    [TestCase("Build", "```powershell\ndotnet build\n```", "howto")]
    [TestCase("Storage", "We chose YAML since it diffs well.", "decision")]
    [TestCase("Storage", "YAML, because it diffs well.", "decision")]
    [TestCase("Storage", "Files never hold secrets because they are committed.", "rule")]
    [TestCase("Layout", "The CLI lives in RepoDocsCli.", "fact")]
    [TestCase("Example", "```razor\n<div />\n```", "fact")]
    public void KindIsGuessedFromHeadingAndBody(string heading, string body, string kind) =>
        Assert.That(KindGuess.Guess(new ImportCandidate([heading], heading, body, 1)), Is.EqualTo(kind));

    [TestCase("Never use `_` prefixes on fields", "never-use-prefixes-on-fields")]
    [TestCase("Don't edit .repo-docs by hand", "dont-edit-repo-docs-by-hand")]
    [TestCase("A very long summary that keeps going well past the limit", "a-very-long-summary-that-keeps-going")]
    [TestCase("!!!", "entry")]
    public void EntryIdsAreKebabCaseFromTheSummary(string summary, string id)
    {
        Assert.That(EntryId.FromSummary(summary), Is.EqualTo(id));
        Assert.That(EntryId.IsValid(EntryId.FromSummary(summary)), Is.True);
    }

    [Test]
    public void UniqueIdsGetANumberSuffix() =>
        Assert.That(EntryId.Unique("style", new HashSet<string> { "style", "style-2" }), Is.EqualTo("style-3"));
}
