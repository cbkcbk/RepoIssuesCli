using RepoDocsCli.Features.ClaudeMd;
using RepoDocsCli.Features.Docs;

namespace RepoDocsCli.Tests.Features;

public class ClaudeMdBlockTests
{
    static readonly DocsConfig Config = new()
    {
        Kinds = new Dictionary<string, KindConfig>
        {
            ["rule"] = new() { Render = RenderMode.Index },
            ["note"] = new() { Render = RenderMode.Always },
            ["fact"] = new() { Render = RenderMode.Never },
        },
    };

    static FeatureEntry Entry(string id, string kind, string summary, string? body = null) =>
        new() { Id = id, Kind = kind, Summary = summary, Body = body };

    static DocsSnapshot Snapshot(RepoDocs? repo = null, params Feature[] features) =>
        new(repo ?? new RepoDocs(), Config, features, []);

    [Test]
    public void EmptySnapshotRendersOnlyTheMarkers()
    {
        Assert.That(ClaudeMdBlock.Render(Snapshot()), Is.EqualTo($"{ClaudeMdBlock.BeginLine}\n{ClaudeMdBlock.EndMarker}"));
    }

    [Test]
    public void RendersTheFullLayout()
    {
        var repo = new RepoDocs
        {
            Summary = "Monorepo for the shop",
            Entries =
            [
                Entry("style", "rule", "Use file-scoped namespaces", "No `_` prefix on fields.\n"),
                Entry("build", "note", "Build with dotnet build"),
                Entry("history", "fact", "Started in 2019"),
            ],
        };
        var billing = new Feature
        {
            Id = "billing",
            Status = FeatureStatus.InProgress,
            Summary = "Invoices and payments",
            Entries =
            [
                Entry("rounding", "rule", "Round half to even", "Never round twice."),
                Entry("vat-cache", "note", "VAT rates are cached for an hour", "Clear it with `vat reset`.\n"),
                Entry("origin", "fact", "Ported from the old shop"),
            ],
        };
        var search = new Feature { Id = "search", Status = FeatureStatus.Shipped };

        var block = ClaudeMdBlock.Render(Snapshot(repo, search, billing));

        Assert.That(block, Is.EqualTo(
            """
            <!-- docs:begin (generated by docs render; edit .repo-docs instead) -->
            ## Repo

            Monorepo for the shop

            ### repo/style: Use file-scoped namespaces

            No `_` prefix on fields.

            ### repo/build: Build with dotnet build

            ## Features

            Read a feature with `docs show <id>` (or one entry with `docs show <id>/<entry>`) and search with `docs find <query>`. Never read or edit `.repo-docs/` files directly.

            - billing [in-progress]: Invoices and payments
              - billing/rounding: Round half to even
            - search [shipped]

            ## Feature details

            ### billing/vat-cache: VAT rates are cached for an hour

            Clear it with `vat reset`.
            <!-- docs:end -->
            """.ReplaceLineEndings("\n")));
    }

    [Test]
    public void FeatureIndexPointsAgentsToTheCliInsteadOfTheYaml()
    {
        var block = ClaudeMdBlock.Render(Snapshot(null, new Feature { Id = "search" }));

        Assert.That(block, Does.Contain("## Features\n\n" + ClaudeMdBlock.IndexHint + "\n\n- search"));
        Assert.That(ClaudeMdBlock.IndexHint, Does.Contain("docs show <id>").And.Contain("docs find <query>").And.Not.Contain(".yaml"));
    }

    [TestCase("rule", true)]
    [TestCase("note", true)]
    [TestCase("fact", false)]
    [TestCase("undeclared", false)]
    public void RepoEntriesRenderInFullUnlessTheirKindIsNever(string kind, bool rendered)
    {
        var block = ClaudeMdBlock.Render(Snapshot(new RepoDocs { Entries = [Entry("style", kind, "Use tabs", "Width 4.")] }));

        Assert.That(block.Contains("### repo/style: Use tabs\n\nWidth 4.\n"), Is.EqualTo(rendered), block);
    }

    [TestCase("rule", "  - billing/rounding: Round half to even\n")]
    [TestCase("note", "### billing/rounding: Round half to even\n\nWidth 4.\n")]
    public void FeatureEntriesRenderByKindMode(string kind, string expected)
    {
        var feature = new Feature { Id = "billing", Entries = [Entry("rounding", kind, "Round half to even", "Width 4.")] };

        var block = ClaudeMdBlock.Render(Snapshot(null, feature));

        Assert.That(block, Does.Contain(expected));
        Assert.That(block.Split("rounding").Length - 1, Is.EqualTo(1));
    }

    [TestCase("fact")]
    [TestCase("undeclared")]
    public void FeatureEntriesWithNeverOrUndeclaredKindsAreSkipped(string kind)
    {
        var feature = new Feature { Id = "billing", Entries = [Entry("rounding", kind, "Round half to even")] };

        var block = ClaudeMdBlock.Render(Snapshot(null, feature));

        Assert.That(block, Does.Not.Contain("rounding"));
        Assert.That(block, Does.Contain("- billing [proposed]\n"));
        Assert.That(block, Does.Not.Contain("## Feature details"));
    }

    [Test]
    public void DeprecatedFeaturesAndTheirEntriesAreSkipped()
    {
        var old = new Feature
        {
            Id = "old-billing",
            Status = FeatureStatus.Deprecated,
            Summary = "Legacy invoices",
            Entries = [Entry("rounding", "rule", "Round down"), Entry("notes", "note", "Do not touch")],
        };

        var block = ClaudeMdBlock.Render(Snapshot(null, old, new Feature { Id = "search" }));

        Assert.That(block, Does.Not.Contain("old-billing"));
        Assert.That(block, Does.Contain("- search [proposed]"));
    }

    [Test]
    public void FeaturesAreSortedByIdAndEntriesKeepFileOrder()
    {
        var zeta = new Feature { Id = "zeta", Entries = [Entry("b", "rule", "Second"), Entry("a", "rule", "First")] };
        var alpha = new Feature { Id = "alpha" };

        var block = ClaudeMdBlock.Render(Snapshot(null, zeta, alpha));

        Assert.That(block, Does.Contain("- alpha [proposed]\n- zeta [proposed]\n  - zeta/b: Second\n  - zeta/a: First\n"));
    }

    [Test]
    public void OutputIsDeterministic()
    {
        var features = new[] { new Feature { Id = "search", Created = DateTimeOffset.UtcNow }, new Feature { Id = "billing", Summary = "Bills" } };

        var first = ClaudeMdBlock.Render(Snapshot(null, features));
        var second = ClaudeMdBlock.Render(Snapshot(null, [.. features.Reverse()]));

        Assert.That(second, Is.EqualTo(first));
        Assert.That(first, Does.Not.Contain(DateTimeOffset.UtcNow.Year.ToString()));
    }

    [Test]
    public void MultiLineSummariesCollapseAndCrlfBodiesBecomeLf()
    {
        var repo = new RepoDocs { Entries = [Entry("style", "rule", "Use tabs\r\neverywhere", "\nLine one\r\nLine two\r\n\r\n")] };

        var block = ClaudeMdBlock.Render(Snapshot(repo));

        Assert.That(block, Does.Contain("### repo/style: Use tabs everywhere\n\nLine one\nLine two\n<!-- docs:end -->"));
        Assert.That(block, Does.Not.Contain("\r"));
    }
}
