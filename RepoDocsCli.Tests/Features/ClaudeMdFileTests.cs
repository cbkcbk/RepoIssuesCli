using RepoDocsCli.Features.ClaudeMd;
using RepoDocsCli.Features.Docs;

namespace RepoDocsCli.Tests.Features;

public class ClaudeMdFileTests
{
    const string Block = "<!-- docs:begin (generated by docs render; edit .repo-docs instead) -->\nnew\n<!-- docs:end -->";

    [TestCase(null)]
    [TestCase("")]
    public void MissingOrEmptyFileBecomesTheBlock(string? existing) =>
        Assert.That(ClaudeMdFile.Apply(existing, Block), Is.EqualTo(Block + "\n"));

    [TestCase("# Rules", "# Rules\n\n")]
    [TestCase("# Rules\n", "# Rules\n\n")]
    [TestCase("# Rules\n\n", "# Rules\n\n")]
    [TestCase("# Rules\r\n", "# Rules\r\n\n")]
    [TestCase("# Rules\r\n\r\n", "# Rules\r\n\r\n")]
    public void FileWithoutMarkersGetsTheBlockAppended(string existing, string prefix) =>
        Assert.That(ClaudeMdFile.Apply(existing, Block), Is.EqualTo(prefix + Block + "\n"));

    [Test]
    public void ExistingBlockIsReplacedAndTheRestKeptByteForByte()
    {
        const string before = "﻿# Rules\r\n\r\nKeep this.  \r\n";
        const string after = "\r\n## Mine\r\nTrailing text without newline";
        var existing = before + "<!-- docs:begin (old wording) -->\r\nold\r\nlines\r\n<!-- docs:end -->" + after;

        var updated = ClaudeMdFile.Apply(existing, Block);

        Assert.That(updated, Is.EqualTo(before + Block + after));
    }

    [Test]
    public void ApplyIsIdempotent()
    {
        var once = ClaudeMdFile.Apply("# Rules\n", Block);

        Assert.That(ClaudeMdFile.Apply(once, Block), Is.EqualTo(once));
    }

    [Test]
    public void BlockAtTheStartAfterAByteOrderMarkIsFound()
    {
        var existing = "﻿<!-- docs:begin -->\nold\n<!-- docs:end -->\n";

        Assert.That(ClaudeMdFile.Apply(existing, Block), Is.EqualTo("﻿" + Block + "\n"));
    }

    [Test]
    public void MarkersInsideALineAreNotMarkers()
    {
        const string existing = "Write `<!-- docs:begin` and `<!-- docs:end -->` by hand? No.\n";

        Assert.That(ClaudeMdFile.Apply(existing, Block), Is.EqualTo(existing + "\n" + Block + "\n"));
    }

    [TestCase("<!-- docs:begin -->\nold\n")]
    [TestCase("old\n<!-- docs:end -->\n")]
    [TestCase("<!-- docs:end -->\n<!-- docs:begin -->\n")]
    [TestCase("<!-- docs:begin -->\n<!-- docs:end -->\n<!-- docs:begin -->\n<!-- docs:end -->\n")]
    public void BrokenMarkersAreAFileError(string existing)
    {
        var exception = Assert.Throws<DocsFileException>(() => ClaudeMdFile.Apply(existing, Block));

        Assert.That(exception!.Error.FileName, Is.EqualTo("CLAUDE.md"));
    }

    [Test]
    public void IsStaleComparesTheFileWithTheRenderedBlock()
    {
        using var repo = new TempRepo();
        var snapshot = new DocsSnapshot(new RepoDocs(), DocsConfig.Default(), [new Feature { Id = "billing" }], []);

        Assert.That(ClaudeMdFile.IsStale(repo.Root, snapshot), Is.True);

        ClaudeMdFile.Write(repo.Root, snapshot);
        Assert.That(ClaudeMdFile.IsStale(repo.Root, snapshot), Is.False);

        var changed = snapshot with { Features = [new Feature { Id = "billing", Summary = "Bills" }] };
        Assert.That(ClaudeMdFile.IsStale(repo.Root, changed), Is.True);
    }

    [Test]
    public void WriteReportsCreatedChangedAndUnchanged()
    {
        using var repo = new TempRepo();
        var snapshot = new DocsSnapshot(new RepoDocs(), DocsConfig.Default(), [], []);

        var created = ClaudeMdFile.Write(repo.Root, snapshot);
        var unchanged = ClaudeMdFile.Write(repo.Root, snapshot);
        var changed = ClaudeMdFile.Write(repo.Root, snapshot with { Features = [new Feature { Id = "billing" }] });

        Assert.That(created, Is.EqualTo(new RenderResult(ClaudeMdFile.PathIn(repo.Root), Created: true, Changed: true, Stale: true)));
        Assert.That(unchanged, Is.EqualTo(new RenderResult(ClaudeMdFile.PathIn(repo.Root), Created: false, Changed: false, Stale: false)));
        Assert.That(changed, Is.EqualTo(new RenderResult(ClaudeMdFile.PathIn(repo.Root), Created: false, Changed: true, Stale: true)));
    }
}
