using RepoDocsCli.Features.Docs;

namespace RepoDocsCli.Features.ClaudeMd;

public static class ClaudeMdBlock
{
    public const string BeginMarker = "<!-- docs:begin";
    public const string BeginLine = BeginMarker + " (generated by docs render; edit .repo-docs instead) -->";
    public const string EndMarker = "<!-- docs:end -->";

    public static string Render(DocsSnapshot snapshot)
    {
        var features = snapshot.Features
            .Where(feature => feature.Status != FeatureStatus.Deprecated)
            .OrderBy(feature => feature.Id, StringComparer.Ordinal)
            .ToList();

        string[] sections =
        [
            RepoSection(snapshot),
            FeatureIndex(features, snapshot.Config),
            FeatureDetails(features, snapshot.Config),
        ];
        var content = string.Join("\n\n", sections.Where(section => section.Length > 0));

        return content.Length == 0 ? $"{BeginLine}\n{EndMarker}" : $"{BeginLine}\n{content}\n{EndMarker}";
    }

    public static RenderMode ModeOf(FeatureEntry entry, DocsConfig config) =>
        entry.Kind is { } kind && config.Kinds.TryGetValue(kind, out var settings) ? settings.Render : RenderMode.Never;

    static string RepoSection(DocsSnapshot snapshot)
    {
        var parts = new List<string>();
        if (OneLine(snapshot.Repo.Summary) is { Length: > 0 } summary)
            parts.Add(summary);

        parts.AddRange(snapshot.Repo.Entries
            .Where(entry => ModeOf(entry, snapshot.Config) is RenderMode.Always or RenderMode.Index)
            .Select(entry => FullEntry(FeatureId.RepoFileStem, entry)));

        return parts.Count == 0 ? "" : "## Repo\n\n" + string.Join("\n\n", parts);
    }

    static string FeatureIndex(IReadOnlyList<Feature> features, DocsConfig config)
    {
        if (features.Count == 0)
            return "";

        var lines = new List<string> { "## Features", "", $"Each feature lives in `{RepoLocator.DocsFolderName}/<id>{DocsStore.Extension}`.", "" };
        foreach (var feature in features)
        {
            lines.Add("- " + Labeled($"{feature.Id} [{StatusName(feature.Status)}]", feature.Summary));
            lines.AddRange(feature.Entries
                .Where(entry => ModeOf(entry, config) == RenderMode.Index)
                .Select(entry => "  - " + Labeled(Address(feature.Id, entry), entry.Summary)));
        }

        return string.Join("\n", lines);
    }

    static string FeatureDetails(IReadOnlyList<Feature> features, DocsConfig config)
    {
        var entries = features
            .SelectMany(feature => feature.Entries
                .Where(entry => ModeOf(entry, config) == RenderMode.Always)
                .Select(entry => FullEntry(feature.Id, entry)))
            .ToList();

        return entries.Count == 0 ? "" : "## Feature details\n\n" + string.Join("\n\n", entries);
    }

    static string FullEntry(string owner, FeatureEntry entry)
    {
        var heading = "### " + Labeled(Address(owner, entry), entry.Summary);
        return Body(entry.Body) is { Length: > 0 } body ? $"{heading}\n\n{body}" : heading;
    }

    static string Address(string owner, FeatureEntry entry) => EntryId.Address(owner, entry.Id ?? "?");

    static string Labeled(string label, string? summary) =>
        OneLine(summary) is { Length: > 0 } text ? $"{label}: {text}" : label;

    static string OneLine(string? text) => text is null ? "" : text.ReplaceLineEndings(" ").Trim();

    static string Body(string? body) => body is null ? "" : body.ReplaceLineEndings("\n").TrimEnd().TrimStart('\n');

    static string StatusName(FeatureStatus status) => status switch
    {
        FeatureStatus.Proposed => "proposed",
        FeatureStatus.Planned => "planned",
        FeatureStatus.InProgress => "in-progress",
        FeatureStatus.Shipped => "shipped",
        FeatureStatus.Deprecated => "deprecated",
        _ => status.ToString(),
    };
}
