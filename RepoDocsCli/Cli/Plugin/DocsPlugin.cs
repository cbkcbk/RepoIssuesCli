using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using RepoCli.Core.Cli.Plugin;
using RepoDocsCli.Features.Docs;

namespace RepoDocsCli.Cli.Plugin;

public sealed partial class DocsPlugin : IPluginSource
{
    public const string Name = "docs";
    public const string HooksPath = "hooks/hooks.json";
    const string Summary = "Find, maintain and prune agent docs stored in the repository with the docs CLI, with hooks that push matching docs and flag stale ones.";

    static readonly Dictionary<string, string> KindUses = new()
    {
        ["rule"] = "Something to always or never do in this code. Shown as one line in CLAUDE.md.",
        ["fact"] = "How something works or where it lives; current state, not history.",
        ["gotcha"] = "A trap: surprising behaviour that has bitten someone.",
        ["howto"] = "Steps for a recurring task (build, release, add a migration). Shown as one line in CLAUDE.md.",
        ["decision"] = "Why something is the way it is: the choice and its reason. History, so `docs for` leaves it out.",
        ["plan"] = "Work in progress as steps linked to issues. Only shown while its feature is `in-progress`.",
    };

    public static IReadOnlyList<GeneratedFile> Generate(string repoRoot) =>
        PluginGenerator.Generate(repoRoot, new PluginDefinition(Name, Summary, RepoCliApp.Version(typeof(DocsPlugin).Assembly), Skill(), [new GeneratedFile(HooksPath, Hooks())]));

    static string Hooks() => PluginGenerator.Json(new JsonObject
    {
        ["description"] = "docs plugin: push matching docs after Read/Edit/Write, record the starting HEAD, and flag docs affected by changes made in the session on Stop.",
        ["hooks"] = new JsonObject
        {
            ["SessionStart"] = new JsonArray(Matcher(null, "session-start", 10)),
            ["PostToolUse"] = new JsonArray(Matcher("Read", "read", 10), Matcher("Edit|Write|MultiEdit", "edit", 10)),
            ["Stop"] = new JsonArray(Matcher(null, "stop", 60)),
        },
    });

    static JsonObject Matcher(string? matcher, string hookEvent, int timeout)
    {
        var entry = new JsonObject();
        if (matcher is not null)
            entry["matcher"] = matcher;
        entry["hooks"] = new JsonArray(new JsonObject
        {
            ["type"] = "command",
            ["command"] = $"docs hook {hookEvent}",
            ["timeout"] = timeout,
        });
        return entry;
    }

    static string KindRows() => string.Join('\n', DocsConfig.Default().Kinds.Select(kind =>
        $"| `{kind.Key}` | {KindUses.GetValueOrDefault(kind.Key, "")} | {Kebab(kind.Value.Push)} | {Kebab(kind.Value.Render)} |"));

    static string Kebab(Enum value) => Capital().Replace(value.ToString(), "-$0").ToLowerInvariant();

    [GeneratedRegex("(?<!^)[A-Z]")]
    private static partial Regex Capital();

    static string Skill() =>
        $$"""
          ---
          name: {{Name}}
          description: Look up and maintain the repo's agent docs (rules, facts, gotchas, how-tos, decisions, plans) in `.repo-docs/` with the `docs` CLI. Use before working in an area of the code, when you need to know how something works here, when recording a rule, gotcha or decision, after changing code that docs describe, when condensing or pruning docs, or when the repo contains `.repo-docs/`.
          ---

          <!-- Generated by `docs generate-plugin` (debug build). Edit RepoDocsCli/Cli/Plugin/DocsPlugin.cs and regenerate. -->

          # docs

          Docs are YAML files in `.repo-docs/`, committed alongside the code: one file per feature, `repo.yaml` for repo-wide entries and `config.yaml` for the entry kinds. The goals are to keep docs condensed, make the relevant ones easy to find, and remove stale ones.

          **Never edit, create, rename or delete files in `.repo-docs/` directly** — not with Edit/Write, not with shell commands, not even for a small fix. Always go through the `docs` CLI (`docs add`, `docs edit`, `docs rm`, `docs touch`, `docs check --fix`). It validates every change, anchors hints to the current code, stamps `created`, `updated` and `read`, stages files with git and holds the lock; hand edits silently break all of that. Read docs with `docs show`, `docs for` and `docs find`, not by opening the YAML. If the CLI can't make the change you need (such as a new kind in `config.yaml`, reordering entries or moving an entry to another feature), tell the user instead of editing the YAML. The only exception is resolving a git merge conflict in those files, followed by `docs check`.

          ## Calling the CLI

          - Pass `--json` on every call. It suppresses prompts and prints only JSON on stdout; errors go to stderr.
          - Option details for any command: `docs <command> --help`.
          - Missing from PATH: `dotnet tool install -g RepoDocsCli`.

          | Exit code | Meaning |
          |---|---|
          {{PluginGenerator.ExitCodeRows()}}

          ## Commands

          | Command | Purpose |
          |---|---|
          {{PluginGenerator.CommandRows(PluginGenerator.Commands(Name, console => DocsApp.Create(console, console)))}}

          `docs hook` is called by this plugin's hooks; you don't run it.

          An `<address>` is `feature` (a kebab-case id such as `billing`), `feature/entry` (`billing/rounding`), `repo` (the `repo.yaml` entries) or `repo/entry`.

          ## Kinds

          The kinds of a new repo. `config.yaml` may declare others; an undeclared kind is rejected.

          | Kind | Use for | Pushed by hooks | In CLAUDE.md |
          |---|---|---|---|
          {{KindRows()}}

          Feature status: `proposed`, `planned`, `in-progress`, `shipped`, `deprecated`.

          ## Looking things up

          1. Before working in an area: `docs for <path> --json`. It returns the `repo.yaml` entries plus the entries whose paths or anchors match the file or folder, without decisions, and plans only for `in-progress` features. Bodies up to 600 characters are included; `hasBody` without `body` means there is more.
          2. Search by topic: `docs find "<words>" --json`.
          3. Read one entry in full: `docs show <feature>/<entry> --json`. Prefer single entries to `docs show <feature> --full` to save context. `show` records the read, which keeps useful docs from being pruned as unread.
          4. Overview: `docs list --json`, and `docs show <feature> --json` for a feature's entry summaries.

          The plugin's hooks also push matching entries after you read or edit a file, by each kind's push policy: the whole entry when it is short, otherwise its summary and the `docs show` command. Each entry is pushed once per session.

          ## Writing docs

          Keep entries condensed: a one-line summary that stands alone, a body only when it adds something (up to 600 characters is pushed in full), one point per entry. Run `docs find` first and update an existing entry rather than adding a near-duplicate. Record what the code can't tell the next agent; don't restate the code.

          ```sh
          docs add billing --status in-progress --summary "Invoices and payments" --path App/Features/Billing/ --json
          docs add billing/rounding --kind rule --summary "Round half to even" --body "Use MidpointRounding.ToEven." --anchor App/Features/Billing/Money.cs:42 --json
          docs add billing --entry --kind gotcha --summary "VAT rates are cached for an hour" --json
          docs add repo/style --kind rule --summary "Use file-scoped namespaces" --json
          docs edit billing/rounding --summary "Round once, half to even" --add-keyword money --json
          docs edit billing --status shipped --json
          docs rm billing/rounding --force --json
          ```

          - `--entry` derives the entry id from the summary. An explicit id is lowercase kebab-case.
          - Hints: `--path` (a file or folder), `--anchor path:line` or `path:line-end` (anchored to the code there, so it follows the code when lines move) and `--keyword`. On `edit`: `--add-path`/`--remove-path`, `--add-anchor`/`--remove-anchor` and `--add-keyword`/`--remove-keyword`, all repeatable. An entry without its own paths or anchors applies wherever its feature does.
          - Body: `--body <text>`, `--body-file <path>` or `--body-stdin`; `--clear-body` removes it.
          - Other edits: `--kind`, `--status` (features), `--id <new-id>` to rename.
          - Plans: `docs add billing/rollout --kind plan --summary "Roll out the new invoices" --step "Schema and store #23 #24" --step "Write the migration guide" --json`. Trailing `#n` tokens link issues. On `edit`: `--add-step "Release #30"`, `--set-step 2="Write the guide #31"`, `--step-issues 1=23,24` (`1=` clears them) and `--remove-step 3`. Steps are numbered from 1 as they were before the edit, also when one call has several step options. Progress is derived from the linked issues; never write it down.
          - Re-anchor code that changed: `docs edit <address> --add-anchor path:line` on the same path and line replaces the anchor.
          - Still correct after its code changed: `docs touch <address>`.
          - Exit code 2 with problems on stderr means the change was refused (an undeclared kind, a multi-line summary, a duplicate id); nothing was written.

          ## After changing code

          Run `docs affected --json` before you finish. It lists docs whose anchors or paths your change hit but that you did not update (`--since <ref>` includes committed work). For each one, read it against the code, then fix it with `docs edit`, or run `docs touch <address>` when it is still correct. The plugin's Stop hook runs this for the whole session and stops you once with the list.

          Commit the changed `.repo-docs/` files and `CLAUDE.md` with the code.

          ## Condensing and pruning

          Start with `docs budget --json`: what every session pays up front (`CLAUDE.md`, its imports and the generated block) against what is fetched on demand or pushed by hooks, with the largest entries as condensing targets (`--top N`, `--by feature` or `--by kind`). Run it again at the end to measure the gain.

          1. `docs prune --json` lists stale candidates, strongest reason first, each with `reasons` and a `suggestion: { action, command }`. Act on every candidate through the CLI:
             - `delete` (`Orphaned`, `DeprecatedOrphan`): check that the code is really gone, then `docs rm <address> --force`.
             - `re-anchor` (`BrokenAnchor`, `DeadPath`): find where the code went and replace the hint (`--remove-anchor`/`--add-anchor`, `--remove-path`/`--add-path`), or delete the entry when it no longer applies.
             - `review` (`ChangedAnchor`, `Unread`): read the entry and the code; fix it with `docs edit` and re-anchor, `docs touch` it when it still holds, or delete it when it is useless.
             - `convert-to-decision` (`ShippedPlan`): rewrite it as what was decided and why with `docs edit <address> --kind decision --summary ... --body ...` (or `--kind fact`), or delete it.
             - `collapse-steps` (`CollapsibleStep`): remove or merge the done steps with `--remove-step`/`--set-step`.
          2. Condense, biggest `docs budget` targets first: merge near-duplicates (edit one, `docs rm` the other), shorten long bodies, split an entry that mixes several points, and move text that only matters in one area out of the always-loaded `CLAUDE.md` into entries (`docs import` turns its sections into entries for review).
          3. `docs check --fix --json` repairs mechanical drift (moved anchors, merge conflicts, hand-edit stamps, a stale CLAUDE.md block) and lists what is left. Fix the rest with the commands above; exit code 1 means errors remain.
          4. `docs render` refreshes the generated block in `CLAUDE.md` after rules, how-tos or `repo.yaml` entries change.

          `prune` is advice. Unless the user asked you to prune, ask before deleting docs you didn't write.
          """;
}
