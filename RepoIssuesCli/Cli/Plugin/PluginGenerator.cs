using System.ComponentModel;
using System.Reflection;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Xml.Linq;
using RepoIssuesCli.Features.Issues;
using Spectre.Console;

namespace RepoIssuesCli.Cli.Plugin;

public sealed record GeneratedFile(string Path, string Content);

public static class PluginGenerator
{
    public const string MarketplaceName = "repo-issues";
    public const string PluginName = "issues";
    const string Summary = "Track work as issues stored in the repository with the issues CLI.";

    static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = true };

    public static IReadOnlyList<GeneratedFile> Generate(string repoRoot)
    {
        var version = typeof(PluginGenerator).Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion.Split('+')[0] ?? "0.0.0";
        var owner = ExistingOwner(repoRoot) ?? GitOwner(repoRoot) ?? "RepoIssuesCli";

        var marketplace = new JsonObject
        {
            ["name"] = MarketplaceName,
            ["description"] = "Claude Code plugin for the issues CLI (RepoIssuesCli).",
            ["owner"] = new JsonObject { ["name"] = owner },
            ["plugins"] = new JsonArray(new JsonObject
            {
                ["name"] = PluginName,
                ["source"] = $"./plugins/{PluginName}",
                ["description"] = Summary,
                ["version"] = version,
            }),
        };

        var manifest = new JsonObject
        {
            ["name"] = PluginName,
            ["version"] = version,
            ["description"] = Summary,
            ["author"] = new JsonObject { ["name"] = owner },
        };

        return
        [
            new(".claude-plugin/marketplace.json", marketplace.ToJsonString(JsonOptions) + "\n"),
            new($"plugins/{PluginName}/.claude-plugin/plugin.json", manifest.ToJsonString(JsonOptions) + "\n"),
            new($"plugins/{PluginName}/skills/{PluginName}/SKILL.md", Skill()),
        ];
    }

    public static void Write(string repoRoot, IEnumerable<GeneratedFile> files)
    {
        foreach (var file in files)
        {
            var path = Path.Combine(repoRoot, file.Path);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, file.Content);
        }
    }

    static string Skill() =>
        $$"""
        ---
        name: {{PluginName}}
        description: Track work as issues in the repo's `.repo-issues/` folder with the `issues` CLI. Use when filing, finding, updating, blocking or closing an issue, picking the next task, or when the repo contains `.repo-issues/`.
        ---

        <!-- Generated by `issues generate-plugin` (debug build). Edit RepoIssuesCli/Cli/Plugin/PluginGenerator.cs and regenerate. -->

        # issues

        Issues are JSON files in `.repo-issues/`, committed alongside the code. Change them through the `issues` CLI so numbers, blockers and timestamps stay consistent.

        ## Calling the CLI

        - Pass `--json` on every call. It suppresses prompts and prints only JSON on stdout; errors go to stderr.
        - Option details for any command: `issues <command> --help`.
        - Missing from PATH: `dotnet tool install -g RepoIssuesCli`.

        | Exit code | Meaning |
        |---|---|
        {{ExitCodeRows()}}

        ## Commands

        | Command | Purpose |
        |---|---|
        {{CommandRows()}}

        `<ref>` accepts a number (`3` or `0003`), a unique name prefix, a full title (`0003 Fix login`) or the id. Prefer the number.

        Status: {{Values<IssueStatus>()}}. Priority: {{Values<IssuePriority>()}}.

        ## Workflow

        1. Pick: `issues list --ready --json` returns unblocked Open and InProgress issues, highest priority first.
        2. Start: `issues status <n> InProgress --json`.
        3. Point at code with repo-relative `-l path:line:col`, on `new` or via `edit --add-location`.
        4. Blockers: `issues edit <n> --add-blocker <m> --json` means n waits on m. A blocker that would create a cycle is rejected with exit code 2.
        5. Finish: `issues status <n> Done --json`, then commit the changed `.repo-issues/*.json` files with the code change.
        6. After merging branches or hand-editing files, run `issues validate --json`. Exit code 1 means it found problems, such as duplicate numbers or missing blockers, listed in its output.
        """.ReplaceLineEndings("\n") + "\n";

    static string ExitCodeRows() => string.Join('\n', typeof(ExitCodes)
        .GetFields(BindingFlags.Public | BindingFlags.Static)
        .Select(field => $"| {field.GetValue(null)} | {field.GetCustomAttribute<DescriptionAttribute>()?.Description} |"));

    static string CommandRows() => string.Join('\n', CommandModel().Select(command => $"| `{command.Usage}` | {command.Description} |"));

    static string Values<T>() where T : struct, Enum => string.Join(", ", Enum.GetNames<T>().Select(name => $"`{name}`"));

    static IReadOnlyList<(string Usage, string Description)> CommandModel()
    {
        var writer = new StringWriter();
        var console = AnsiConsole.Create(new AnsiConsoleSettings
        {
            Ansi = AnsiSupport.No,
            ColorSystem = ColorSystemSupport.NoColors,
            Out = new AnsiConsoleOutput(writer),
        });
        console.Profile.Width = 100_000;
        IssuesApp.Create(console, console).Run(["cli", "xmldoc"]);

        return XDocument.Parse(writer.ToString()).Root!
            .Elements("Command")
            .Where(command => command.Attribute("Name")!.Value != GeneratePluginCommand.Name)
            .Select(command => (Usage(command), command.Element("Description")?.Value.Trim() ?? ""))
            .ToList();
    }

    static string Usage(XElement command)
    {
        var arguments = command.Element("Parameters")?.Elements("Argument")
            .OrderBy(argument => (int)argument.Attribute("Position")!)
            .Select(argument => argument.Attribute("Required")!.Value == "true"
                ? $"<{argument.Attribute("Name")!.Value}>"
                : $"[{argument.Attribute("Name")!.Value}]") ?? [];
        return string.Join(' ', ["issues", command.Attribute("Name")!.Value, .. arguments]);
    }

    static string? ExistingOwner(string repoRoot)
    {
        var path = Path.Combine(repoRoot, ".claude-plugin", "marketplace.json");
        return File.Exists(path) ? JsonNode.Parse(File.ReadAllText(path))?["owner"]?["name"]?.GetValue<string>() : null;
    }

    static string? GitOwner(string repoRoot) => GitIdentity.Author(repoRoot)?.Split(" <")[0];
}
