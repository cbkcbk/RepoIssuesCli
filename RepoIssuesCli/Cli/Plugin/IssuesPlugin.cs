using RepoCli.Core.Cli.Plugin;
using RepoIssuesCli.Features.Issues;

namespace RepoIssuesCli.Cli.Plugin;

public sealed class IssuesPlugin : IPluginSource
{
    public const string Name = "issues";
    const string Summary = "Track work as issues stored in the repository with the issues CLI.";

    public static IReadOnlyList<GeneratedFile> Generate(string repoRoot) =>
        PluginGenerator.Generate(repoRoot, new PluginDefinition(Name, Summary, RepoCliApp.Version(typeof(IssuesPlugin).Assembly), Skill()));

    static string Skill() =>
        $$"""
          ---
          name: {{Name}}
          description: Track work as issues in the repo's `.repo-issues/` folder with the `issues` CLI. Use when filing, finding, updating, blocking or closing an issue, picking the next task, or when the repo contains `.repo-issues/`.
          ---

          <!-- Generated by `issues generate-plugin` (debug build). Edit RepoIssuesCli/Cli/Plugin/IssuesPlugin.cs and regenerate. -->

          # issues

          Issues are JSON files in `.repo-issues/`, committed alongside the code.

          **Never edit, create, rename or delete files in `.repo-issues/` directly** — not with Edit/Write, not with shell commands, not even for a small fix. Always go through the `issues` CLI. It assigns numbers under a lock, keeps file names in sync with names and numbers via `git mv`, rewrites blocker references, and stamps authors and timestamps; hand edits silently break all of that. If the CLI can't make the change you need, tell the user instead of editing the JSON. The only exception is resolving a git merge conflict in those files, followed by `issues validate`.

          ## Calling the CLI

          - Pass `--json` on every call. It suppresses prompts and prints only JSON on stdout; errors go to stderr.
          - Option details for any command: `issues <command> --help`.
          - Missing from PATH: `dotnet tool install -g RepoIssuesCli`.

          | Exit code | Meaning |
          |---|---|
          {{PluginGenerator.ExitCodeRows()}}

          ## Commands

          | Command | Purpose |
          |---|---|
          {{PluginGenerator.CommandRows(PluginGenerator.Commands(Name, console => IssuesApp.Create(console, console)))}}

          `<ref>` accepts a number (`3` or `0003`), a unique name prefix, a full title (`0003 Fix login`) or the id. Prefer the number.

          Status: {{PluginGenerator.Values<IssueStatus>()}}. Priority: {{PluginGenerator.Values<IssuePriority>()}}.

          ## Creating an issue

          Create an issue in one call. The name is positional and every other field is a flag. `-t`, `-b` and `-l` repeat:

          ```sh
          issues new "Login fails on empty password" -d "Submitting an empty password returns 500 instead of a validation error." -p High -t bug -t auth -b 3 -l src/Auth/Login.cs:42:9 --json
          ```

          The output is the created issue; read its `number` to refer to it later.

          Author: when the user asks for the issue, keep the default (their git identity). When you file an issue on your own initiative, such as a bug or follow-up you noticed while working, mark it as yours with `--author "Claude"`.

          ## Workflow

          1. Pick: `issues list --ready --json` returns unblocked Open and InProgress issues, highest priority first.
          2. Start: `issues status <n> InProgress --json`.
          3. Point at code with repo-relative `-l path:line:col` (or `path:line-end` for a range), on `new` or via `edit --add-location`. Locations are anchored to the code there, so they follow it when lines move.
          4. Blockers: `issues edit <n> --add-blocker <m> --json` means n waits on m. A blocker that would create a cycle is rejected with exit code 2.
          5. Finish: `issues status <n> Done --json`, then commit the changed `.repo-issues/*.json` files with the code change.
          6. After merging branches or resolving a merge conflict, run `issues validate --json`. Exit code 1 means it found problems, such as duplicate numbers or missing blockers, listed in its output. Location warnings (`LocationMoved`, `LocationChanged`, `LocationBroken`) don't fail the run; `issues validate --fix --json` rewrites moved hints. Items with `needsConfirmation` or `LocationChanged` need a look at the code: re-add the location with `edit --remove-location` and `--add-location` if the issue still applies.
          """;
}